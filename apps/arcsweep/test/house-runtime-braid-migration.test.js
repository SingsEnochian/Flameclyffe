import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const migration = fs.readFileSync(path.join(root, 'supabase/migrations/202608140003_house_runtime_braid.sql'), 'utf8');
const streamFunction = fs.readFileSync(path.join(root, 'netlify/functions/house-braid-stream.mts'), 'utf8');
const main = fs.readFileSync(path.join(root, 'apps/arcsweep/src/main.js'), 'utf8');
const client = fs.readFileSync(path.join(root, 'apps/arcsweep/src/house-runtime.js'), 'utf8');

test('Runtime Braid migration creates one append-only private event spine', () => {
  assert.match(migration, /create table if not exists public\.house_runtime_events/i);
  assert.match(migration, /event_sequence bigint generated by default as identity primary key/i);
  assert.match(migration, /idempotency_key text not null unique/i);
  assert.match(migration, /continuity_packet_id text not null references public\.arcsweep_feedback_cycles/i);
  assert.match(migration, /before insert on public\.arcsweep_feedback_cycles/i);
  assert.match(migration, /new\.continuity_packet_id := concat\('braid:', new\.world_id, ':', new\.cycle_id\)/i);
  assert.match(migration, /before update or delete on public\.house_runtime_events/i);
  assert.match(migration, /raise exception 'House Runtime events are append-only'/i);
  assert.match(migration, /alter table public\.house_runtime_events enable row level security/i);
  assert.match(migration, /using \(false\)/i);
  assert.match(migration, /revoke all on public\.house_runtime_events from anon, authenticated/i);
  assert.match(migration, /drop policy if exists "accepted Arcsweep feedback cycles are readable"/i);
  assert.match(migration, /revoke all on public\.arcsweep_feedback_cycles from anon, authenticated/i);
});

test('Runtime Braid command RPC is transaction-scoped, human-gated, and service-role only', () => {
  assert.match(migration, /house_runtime_apply_observation_command\(p_command jsonb\)/i);
  assert.match(migration, /security invoker\s+set search_path = ''/i);
  assert.doesNotMatch(migration, /security definer/i);
  assert.match(migration, /grant select on public\.arcsweep_feedback_cycles to service_role/i);
  assert.match(migration, /grant select, insert on public\.arcsweep_feedback_reviews to service_role/i);
  assert.match(migration, /grant select, insert on public\.arcsweep_deep_time_records to service_role/i);
  assert.match(migration, /pg_advisory_xact_lock\(hashtextextended\(concat\('house-runtime-cycle:', v_cycle_id\), 0\)\)/i);
  assert.match(migration, /command id is already bound to a different lineage/i);
  assert.match(migration, /payload ->> 'idempotency_key' = idempotency_key/i);
  assert.match(migration, /payload -> 'source_receipt_ids' = source_receipt_ids/i);
  assert.match(migration, /DEEPTime admission requires an accepted human review/i);
  assert.match(migration, /pg_advisory_xact_lock/i);
  assert.match(migration, /DEEPTime sequence advanced; rebuild the admission/i);
  assert.match(migration, /unique index if not exists arcsweep_deep_time_records_sequence_lambda_idx/i);
  assert.match(migration, /Observation cycle already has a different human review/i);
  assert.match(migration, /revoke all on function public\.house_runtime_apply_observation_command\(jsonb\) from public, anon, authenticated/i);
  assert.match(migration, /grant execute on function public\.house_runtime_apply_observation_command\(jsonb\) to service_role/i);
});

test('Runtime Braid event spine is published to Realtime through the sealed server stream', () => {
  assert.match(migration, /alter publication supabase_realtime add table public\.house_runtime_events/i);
  assert.match(streamFunction, /table: 'house_runtime_events'/);
  assert.match(streamFunction, /SUPABASE_SERVICE_ROLE_KEY/);
  assert.match(streamFunction, /path: '\/api\/v1\/house\/braid\/stream'/);
});

test('shared observation surfaces mount broker review, DEEPTime, and live cursor controls', () => {
  assert.match(main, /data-action="runtime-observation-review"/);
  assert.match(main, /data-action="runtime-deeptime-admit"/);
  assert.match(main, /startHouseBraidLiveUpdates/);
  assert.match(main, /\['commons', 'feedback', 'deep-observer'\]/);
  assert.match(client, /hearthgate\.runtime-braid-command\/v1/);
  assert.match(client, /last-event-id|cursor/);
  assert.match(client, /credentials: 'same-origin'/);
});
