import { assertValidDeepTheoryRecord } from '../../../starwell/deep-observer/deep-theory-validator.js';
import { sha256Hex } from '../../starwell/src/world-tone-fold-approval.js';
import { DOMAIN_CONTROL_SWEEP_SCHEMA } from './domain-control-bench.js';

export const ARCSWEEP_DEEP_THEORY_CANDIDATE_SCHEMA = 'arcsweep.deep-theory-candidate-receipt/v1';

function invariant(condition, message) {
  if (!condition) throw new Error(`ARCSWEEP_DEEP_THEORY: ${message}`);
}

function clone(value) {
  return structuredClone(value);
}

function sourceLedger(sweep) {
  const sources = [{
    ref: 'arcsweep-domain-sweep',
    dataset: 'Arcsweep',
    record_type: 'derived',
    checksum: sweep.sweep_fingerprint,
    note: `Bidirectional domain control sweep ${sweep.sweep_id}.`,
  }];
  for (const [index, ref] of (sweep.profile.source_refs || []).entries()) {
    sources.push({
      ref: `external-${index + 1}`,
      dataset: 'external',
      record_type: 'recorded',
      checksum: null,
      note: ref,
    });
  }
  return sources;
}

function findingsFromSweep(sweep) {
  const sourceRefs = ['arcsweep-domain-sweep'];
  const findings = [{
    id: 'topology-regime',
    kind: 'regime',
    text: `The bidirectional normal-form sweep resolved topology state ${sweep.summary.topology_state} with up to ${sweep.summary.max_equilibrium_count} equilibria.`,
    source_refs: sourceRefs,
    confidence: null,
  }, {
    id: 'branch-transitions',
    kind: 'branching',
    text: `${sweep.summary.branch_transition_count} branch-transition observations occurred across the forward and reverse paths.`,
    source_refs: sourceRefs,
    confidence: null,
  }];
  if (sweep.hysteresis.detected) {
    findings.push({
      id: 'hysteresis-witness',
      kind: 'hysteresis',
      text: `Forward and reverse sweeps occupied different stable branches at ${sweep.hysteresis.witness_count} matched control samples; normal-form loop area ${sweep.hysteresis.loop_area}.`,
      source_refs: sourceRefs,
      confidence: null,
    });
  } else {
    findings.push({
      id: 'hysteresis-not-witnessed',
      kind: 'limitation',
      text: 'This sweep did not witness forward/reverse stable-branch separation. Absence in one sampled sweep is not evidence that path dependence is impossible under other controls.',
      source_refs: sourceRefs,
      confidence: null,
    });
  }
  return findings;
}

export async function createDeepTheoryCandidateFromDomainSweep({
  sweep,
  title = null,
  summary = null,
  generatedAt,
} = {}) {
  invariant(sweep?.schema === DOMAIN_CONTROL_SWEEP_SCHEMA, 'a receipted domain control sweep is required');
  invariant(typeof sweep.sweep_fingerprint === 'string' && sweep.sweep_fingerprint.length === 64, 'sweep fingerprint is required');
  const createdAt = generatedAt ?? sweep.generated_at ?? new Date().toISOString();
  const semantics = clone(sweep.profile.control_semantics);
  const core = {
    schema_version: '0.1.0',
    dataset_kind: 'deep_theory',
    parallel_datasets: ['DEEPStory', 'DEEPTime'],
    created_at: createdAt,
    title: title || `${sweep.profile.name} · ${sweep.summary.topology_state}`,
    summary: summary || `Arcsweep domain-control candidate derived from ${sweep.configuration.swept_label} forward/reverse topology sweep.`,
    domain: sweep.profile.domain,
    theory_kind: 'topology_model',
    status: 'candidate',
    source_refs: sourceLedger(sweep),
    models: [{
      id: 'canonical-cusp-potential/v1',
      name: 'Canonical cusp normal form',
      equation: 'x^3 + a*x + b = 0',
      control_semantics: semantics,
      calibration_state: sweep.profile.calibration.state,
      calibration_note: sweep.profile.calibration.note || null,
      physical_claim: false,
    }],
    findings: findingsFromSweep(sweep),
    source_integrity: {
      raw_sources_immutable: true,
      analyses_append_only: true,
      silent_canonicalisation_forbidden: true,
    },
    review: {
      human_review_required: true,
      reviewed_by: null,
      reviewed_at: null,
      note: 'Generated by Arcsweep as a DEEPTheory candidate. Acceptance remains a separate review action.',
    },
    authority: {
      physical_claim: false,
      canon_commit: false,
      domain_semantics_explicit: true,
      cross_domain_numeric_equivalence_assumed: false,
    },
    append_only_revisions: [],
  };
  const fingerprint = await sha256Hex(core);
  const record = {
    ...core,
    id: `deep-theory-${fingerprint.slice(0, 24)}`,
  };
  assertValidDeepTheoryRecord(record);
  const recordFingerprint = await sha256Hex(record);
  return Object.freeze({
    schema: ARCSWEEP_DEEP_THEORY_CANDIDATE_SCHEMA,
    receipt_id: `arcsweep-theory-${recordFingerprint.slice(0, 24)}`,
    record_fingerprint: recordFingerprint,
    source_sweep_id: sweep.sweep_id,
    source_sweep_fingerprint: sweep.sweep_fingerprint,
    record: Object.freeze(record),
    authority: Object.freeze({
      candidate_only: true,
      human_review_required: true,
      source_sweep_mutable: false,
      canon_commit: false,
      physical_claim: false,
    }),
    created_at: createdAt,
  });
}
