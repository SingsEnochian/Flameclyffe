  packet_id text not null,
  packet_fingerprint text not null check (packet_fingerprint ~ '^[0-9a-f]{64}$'),
  source_receipt_ids jsonb not null default '[]'::jsonb check (jsonb_typeof(source_receipt_ids) = 'array'),
  payload jsonb not null,
  created_at timestamptz not null default now(),
  check (payload ->> 'schema' = 'hearthgate.runtime-braid-event/v1'),
  check (payload ->> 'event_id' = event_id),
  check (payload ->> 'event_type' = event_type),
  check (payload ->> 'idempotency_key' = idempotency_key),
  check (payload ->> 'continuity_packet_id' = continuity_packet_id),
  check (payload ->> 'world_id' = world_id),
  check (payload ->> 'cycle_id' = cycle_id),
  check (payload ->> 'actor_id' = actor_id),
  check ((payload ->> 'occurred_at')::timestamptz = occurred_at),
  check (payload ->> 'packet_id' = packet_id),
  check (payload ->> 'packet_fingerprint' = packet_fingerprint),
  check (payload -> 'source_receipt_ids' = source_receipt_ids)
);

