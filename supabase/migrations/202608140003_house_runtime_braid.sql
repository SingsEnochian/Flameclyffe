  event_id text not null unique,
  idempotency_key text not null unique,
  continuity_packet_id text not null references public.arcsweep_feedback_cycles(continuity_packet_id),
  world_id text not null,
  cycle_id text not null references public.arcsweep_feedback_cycles(cycle_id),
  event_type text not null check (event_type in (
    'observation-receipted',
    'review-accepted',
    'review-archived',
    'review-discarded',
    'deeptime-admitted'
  )),
  actor_id text not null,
