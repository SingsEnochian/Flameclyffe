create or replace function public.house_runtime_apply_observation_command(p_command jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_schema text := p_command ->> 'schema';
  v_command_id text := p_command ->> 'command_id';
  v_action text := p_command ->> 'action';
  v_cycle_id text := p_command ->> 'cycle_id';
  v_review jsonb := p_command -> 'review_row';
  v_deep_time jsonb := p_command -> 'deep_time_row';
  v_event jsonb := p_command -> 'event_row';
  v_cycle public.arcsweep_feedback_cycles%rowtype;
  v_existing_review public.arcsweep_feedback_reviews%rowtype;
  v_existing_deep_time public.arcsweep_deep_time_records%rowtype;
  v_previous_deep_time public.arcsweep_deep_time_records%rowtype;
  v_existing_event public.house_runtime_events%rowtype;
  v_event_sequence bigint;
begin
  if v_schema <> 'hearthgate.runtime-braid-command/v1' then
    raise exception 'Unsupported House Runtime braid command schema';
  end if;
  if coalesce(v_command_id, '') = '' or coalesce(v_cycle_id, '') = '' then
    raise exception 'House Runtime braid command and cycle identifiers are required';
  end if;
  if v_action not in ('review-observation', 'admit-deeptime') then
    raise exception 'Unsupported House Runtime braid command action';
  end if;

  select * into v_existing_event
  from public.house_runtime_events
  where idempotency_key = v_command_id;
  if found then
    if v_existing_event.cycle_id <> v_cycle_id
      or (v_action = 'review-observation' and v_existing_event.event_type <> concat('review-', v_review ->> 'decision'))
      or (v_action = 'admit-deeptime' and v_existing_event.event_type <> 'deeptime-admitted') then
      raise exception 'House Runtime command id is already bound to a different lineage';
    end if;
    return jsonb_build_object(
      'applied', false,
      'idempotent', true,
      'event_id', v_existing_event.event_id,
      'event_sequence', v_existing_event.event_sequence,
      'continuity_packet_id', v_existing_event.continuity_packet_id
    );
  end if;

  perform pg_advisory_xact_lock(hashtextextended(concat('house-runtime-cycle:', v_cycle_id), 0));
  select * into v_cycle
  from public.arcsweep_feedback_cycles
  where cycle_id = v_cycle_id;
  if not found then
    raise exception 'Observation cycle does not exist';
  end if;

  if v_event is null
    or v_event ->> 'event_id' is null
    or v_event ->> 'idempotency_key' <> v_command_id
    or v_event ->> 'cycle_id' <> v_cycle_id
    or v_event ->> 'world_id' <> v_cycle.world_id
    or v_event ->> 'continuity_packet_id' <> v_cycle.continuity_packet_id then
    raise exception 'Runtime Braid Event does not match the command lineage';
  end if;

  if v_action = 'review-observation' then
    if v_review is null
      or v_review ->> 'cycle_id' <> v_cycle_id
      or v_review ->> 'world_id' <> v_cycle.world_id
      or v_review ->> 'continuity_packet_id' <> v_cycle.continuity_packet_id
      or v_review ->> 'decision' not in ('accepted', 'archived', 'discarded') then
      raise exception 'Observation review does not match the command lineage';
    end if;
    if v_event ->> 'event_type' <> concat('review-', v_review ->> 'decision') then
      raise exception 'Runtime Braid review event type does not match the human decision';
    end if;

    insert into public.arcsweep_feedback_reviews (
      review_receipt_id,
      cycle_id,
      continuity_packet_id,
      world_id,
      observation_source,
      decision,
      reviewed_by,
      reviewed_at,
      payload
    ) values (
      v_review ->> 'review_receipt_id',
      v_review ->> 'cycle_id',
      v_review ->> 'continuity_packet_id',
      v_review ->> 'world_id',
      v_review ->> 'observation_source',
      v_review ->> 'decision',
      v_review ->> 'reviewed_by',
      (v_review ->> 'reviewed_at')::timestamptz,
      v_review -> 'payload'
    )
    on conflict (cycle_id) do nothing;

    select * into v_existing_review
    from public.arcsweep_feedback_reviews
    where cycle_id = v_cycle_id;
    if v_existing_review.review_receipt_id <> v_review ->> 'review_receipt_id'
      or v_existing_review.decision <> v_review ->> 'decision' then
      raise exception 'Observation cycle already has a different human review';
    end if;
  else
    if v_deep_time is null
      or v_deep_time ->> 'cycle_id' <> v_cycle_id
      or v_deep_time ->> 'world_id' <> v_cycle.world_id
      or v_deep_time ->> 'continuity_packet_id' <> v_cycle.continuity_packet_id then
      raise exception 'DEEPTime record does not match the command lineage';
    end if;
    if v_event ->> 'event_type' <> 'deeptime-admitted' then
      raise exception 'Runtime Braid DEEPTime event type does not match the command';
    end if;

    select * into v_existing_review
    from public.arcsweep_feedback_reviews
    where cycle_id = v_cycle_id;
    if not found or v_existing_review.decision <> 'accepted' then
      raise exception 'DEEPTime admission requires an accepted human review';
    end if;
    if v_existing_review.review_receipt_id <> v_deep_time ->> 'review_receipt_id' then
      raise exception 'DEEPTime admission names the wrong human review receipt';
    end if;

    perform pg_advisory_xact_lock(hashtextextended(concat(v_cycle.world_id, ':', v_deep_time ->> 'sequence_id'), 0));
    select * into v_previous_deep_time
    from public.arcsweep_deep_time_records
    where world_id = v_cycle.world_id
      and sequence_id = v_deep_time ->> 'sequence_id'
    order by lambda desc
    limit 1;
    if found and (v_deep_time ->> 'lambda')::bigint <> v_previous_deep_time.lambda + 1 then
      raise exception 'DEEPTime sequence advanced; rebuild the admission from the latest accepted record';
    end if;
    if found and v_deep_time #>> '{payload,interval,previous_record_id}' <> v_previous_deep_time.record_id then
      raise exception 'DEEPTime predecessor does not match the latest accepted record';
    end if;
    if not found and v_deep_time #>> '{payload,interval,previous_record_id}' is not null then
      raise exception 'First DEEPTime coordinate cannot name a predecessor';
    end if;

    insert into public.arcsweep_deep_time_records (
      record_id,
      cycle_id,
      continuity_packet_id,
      review_receipt_id,
      world_id,
      sequence_id,
      lambda,
      observed_at,
      record_fingerprint,
      payload
    ) values (
      v_deep_time ->> 'record_id',
      v_deep_time ->> 'cycle_id',
      v_deep_time ->> 'continuity_packet_id',
      v_deep_time ->> 'review_receipt_id',
      v_deep_time ->> 'world_id',
      v_deep_time ->> 'sequence_id',
      (v_deep_time ->> 'lambda')::bigint,
      (v_deep_time ->> 'observed_at')::timestamptz,
      v_deep_time ->> 'record_fingerprint',
      v_deep_time -> 'payload'
    )
    on conflict (cycle_id) do nothing;

    select * into v_existing_deep_time
    from public.arcsweep_deep_time_records
    where cycle_id = v_cycle_id;
    if v_existing_deep_time.record_id <> v_deep_time ->> 'record_id'
      or v_existing_deep_time.review_receipt_id <> v_deep_time ->> 'review_receipt_id' then
      raise exception 'Observation cycle already has a different DEEPTime record';
    end if;
  end if;

  insert into public.house_runtime_events (
    event_id,
    idempotency_key,
    continuity_packet_id,
    world_id,
    cycle_id,
    event_type,
    actor_id,
    occurred_at,
    packet_id,
    packet_fingerprint,
    source_receipt_ids,
    payload
  ) values (
    v_event ->> 'event_id',
    v_event ->> 'idempotency_key',
    v_event ->> 'continuity_packet_id',
    v_event ->> 'world_id',
    v_event ->> 'cycle_id',
    v_event ->> 'event_type',
    v_event ->> 'actor_id',
    (v_event ->> 'occurred_at')::timestamptz,
    v_event ->> 'packet_id',
    v_event ->> 'packet_fingerprint',
    v_event -> 'source_receipt_ids',
    v_event -> 'payload'
  )
  returning event_sequence into v_event_sequence;

  return jsonb_build_object(
    'applied', true,
    'idempotent', false,
    'event_id', v_event ->> 'event_id',
    'event_sequence', v_event_sequence,
    'continuity_packet_id', v_cycle.continuity_packet_id
  );
end;
$$;

revoke all on function public.house_runtime_apply_observation_command(jsonb) from public, anon, authenticated;
grant execute on function public.house_runtime_apply_observation_command(jsonb) to service_role;

