import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);const {compile}=require('../lib/wyrdrune/wyrdrune.cjs');
const source=await readFile(new URL('../scores/wyrdrune/story-soundscape-v0.1.wtl',import.meta.url),'utf8');
const content='// Generated by scripts/wayglass-compile-story-score.mjs from the owner-authored WTL source.\n'+
 'export const STORY_SCORE_SOURCE='+JSON.stringify(source)+';\nexport const STORY_SCORE_IR='+JSON.stringify(compile(source))+';\n';
const target=new URL('../lib/wyrdrune/story-score-program.mjs',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==content)throw new Error('Story score artifact is stale');}
else await writeFile(target,content);
